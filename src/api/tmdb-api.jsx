// Helper used by the newer functions below which is the same "if (!response.ok)"while it blocks the lab functions repeat, written once so we don't copy it 9 more times.
const handleResponse = (response) => {
  if (!response.ok) {
    // TMDB sends an error message in the JSON body, so read it and throw it.
    return response.json().then((error) => {
      throw new Error(error.status_message || "Something went wrong");
    });
  }
  return response.json();
};

// react-query passes { queryKey } to the query function. Our keys look like ["discover", { page: 2 }], so we pull the page back out of the second item.
export const getMovies = ({ queryKey }) => {
  const [, pagePart] = queryKey;
  const { page } = pagePart;
  return fetch(
    `https://api.themoviedb.org/3/discover/movie?api_key=${import.meta.env.VITE_TMDB_KEY}&language=en-US&include_adult=false&include_video=false&page=${page}`
  ).then(handleResponse);
};

